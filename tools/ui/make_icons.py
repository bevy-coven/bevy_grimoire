#!/usr/bin/env python3
"""Draw the editor's icon atlas, `crates/bevy_cauldron/assets/ui/icons.png` (UI-38, #232).

Each icon is 16 x 16 pixels, white on transparent with no soft edges, because bevy_gooey's `Icon` tints a
glyph from the skin. The order and the names come from `ICONS` in `crates/bevy_cauldron/src/icons.rs`
(read between its `icons:begin` and `icons:end` markers), so a name added there needs a drawing here and
`tests/every_toolbar_command_has_an_icon.rs` refuses a sheet that disagrees with the list.

    python3 tools/ui/make_icons.py            # write the sheet
    python3 tools/ui/make_icons.py --preview  # also write a 12x contact sheet to /tmp/icons_preview.png

The glyphs are drawn by hand from the primitives below (nothing is generated by a model), so the sheet is
the repo's own and the licence is the repo's.
"""
import math
import re
import sys
from pathlib import Path

from PIL import Image

ROOT = Path(__file__).resolve().parents[2]
RUST = ROOT / "crates/bevy_cauldron/src/icons.rs"
OUT = ROOT / "crates/bevy_cauldron/assets/ui/icons.png"
CELL = 16
COLUMNS = 8


class Canvas:
    def __init__(self):
        self.on = [[False] * CELL for _ in range(CELL)]

    def px(self, x, y, v=True):
        if 0 <= x < CELL and 0 <= y < CELL:
            self.on[y][x] = v

    def fill(self, x0, y0, x1, y1, v=True):
        for y in range(y0, y1 + 1):
            for x in range(x0, x1 + 1):
                self.px(x, y, v)

    def clear(self, x0, y0, x1, y1):
        self.fill(x0, y0, x1, y1, False)

    def rect(self, x0, y0, x1, y1):
        self.fill(x0, y0, x1, y0)
        self.fill(x0, y1, x1, y1)
        self.fill(x0, y0, x0, y1)
        self.fill(x1, y0, x1, y1)

    def line(self, x0, y0, x1, y1, thick=1):
        n = max(abs(x1 - x0), abs(y1 - y0), 1)
        for i in range(n + 1):
            x = round(x0 + (x1 - x0) * i / n)
            y = round(y0 + (y1 - y0) * i / n)
            self.fill(x, y, x + thick - 1, y + thick - 1)

    def path(self, points, thick=1):
        for (a, b), (c, d) in zip(points, points[1:]):
            self.line(a, b, c, d, thick)

    def poly(self, points):
        """Fill a polygon by testing pixel centres."""
        for y in range(CELL):
            for x in range(CELL):
                cx, cy = x + 0.5, y + 0.5
                inside = False
                j = len(points) - 1
                for i in range(len(points)):
                    xi, yi = points[i]
                    xj, yj = points[j]
                    if (yi > cy) != (yj > cy) and cx < (xj - xi) * (cy - yi) / (yj - yi) + xi:
                        inside = not inside
                    j = i
                if inside:
                    self.px(x, y)

    def ring(self, cx, cy, r):
        for y in range(CELL):
            for x in range(CELL):
                if abs(math.hypot(x + 0.5 - cx, y + 0.5 - cy) - r) <= 0.6:
                    self.px(x, y)

    def mirrored(self):
        c = Canvas()
        c.on = [row[::-1] for row in self.on]
        return c


def undo():
    c = Canvas()
    c.poly([(1.5, 6.5), (6, 2.5), (6, 10.5)])
    c.path([(6, 6), (10, 6), (13, 8), (13, 10), (11, 12), (6, 12)], 2)
    return c


def save():
    c = Canvas()
    c.rect(2, 2, 13, 13)
    c.fill(5, 2, 10, 5)
    c.clear(8, 3, 9, 4)
    c.rect(4, 8, 11, 13)
    return c


def fill_bucket():
    c = Canvas()
    c.poly([(2, 6), (12, 6), (10, 14), (4, 14)])
    c.clear(4, 8, 9, 9)
    c.path([(4, 6), (4, 2), (10, 2), (10, 6)])
    c.fill(13, 8, 13, 11)
    c.fill(12, 11, 14, 13)
    return c


def erase():
    """An eraser: a slanted block with a band across it, and the line it rubs out."""
    c = Canvas()
    c.path([(2, 10), (8, 4), (13, 9), (7, 15), (2, 10)])
    c.line(4, 13, 11, 6)
    c.line(3, 11, 9, 5, 2)
    c.fill(9, 15, 14, 15)
    return c


def move():
    c = Canvas()
    c.fill(7, 3, 8, 12)
    c.fill(3, 7, 12, 8)
    c.poly([(7.5, 0.5), (5, 3.5), (10, 3.5)])
    c.poly([(7.5, 15.5), (5, 12.5), (10, 12.5)])
    c.poly([(0.5, 7.5), (3.5, 5), (3.5, 10)])
    c.poly([(15.5, 7.5), (12.5, 5), (12.5, 10)])
    return c


def clone():
    c = Canvas()
    c.rect(2, 2, 9, 9)
    c.clear(5, 5, 13, 13)
    c.rect(6, 6, 13, 13)
    c.fill(8, 8, 11, 11)
    return c


def note():
    c = Canvas()
    c.rect(1, 2, 14, 11)
    c.poly([(4, 11), (4, 14.5), (8, 11)])
    c.line(4, 5, 11, 5)
    c.line(4, 8, 9, 8)
    return c


def run():
    c = Canvas()
    c.poly([(4, 2), (13, 8), (4, 14)])
    return c


def generate():
    c = Canvas()
    c.poly([(8, 1), (10, 6), (15, 8), (10, 10), (8, 15), (6, 10), (1, 8), (6, 6)])
    return c


def frame():
    c = Canvas()
    for sx, sy in ((2, 2), (13, 2), (2, 13), (13, 13)):
        dx = 1 if sx < 8 else -1
        dy = 1 if sy < 8 else -1
        c.line(sx, sy, sx + 4 * dx, sy)
        c.line(sx, sy, sx, sy + 4 * dy)
    c.fill(7, 7, 8, 8)
    return c


def snip():
    c = Canvas()
    for i in range(2, 14, 3):
        c.fill(i, 2, min(i + 1, 13), 2)
        c.fill(i, 13, min(i + 1, 13), 13)
        c.fill(2, i, 2, min(i + 1, 13))
        c.fill(13, i, 13, min(i + 1, 13))
    c.fill(6, 6, 9, 9)
    c.clear(7, 7, 8, 8)
    return c


def outliner():
    c = Canvas()
    c.fill(2, 2, 4, 4)
    c.line(7, 3, 14, 3)
    c.line(3, 5, 3, 12)
    c.line(3, 8, 5, 8)
    c.fill(6, 7, 8, 9)
    c.line(10, 8, 14, 8)
    c.line(3, 12, 5, 12)
    c.fill(6, 11, 8, 13)
    c.line(10, 12, 14, 12)
    return c


def library():
    c = Canvas()
    for x, y in ((2, 2), (9, 2), (2, 9), (9, 9)):
        c.fill(x, y, x + 4, y + 4)
    return c


def inspector():
    c = Canvas()
    for y, k in ((3, 4), (8, 10), (13, 6)):
        c.line(1, y, 14, y)
        c.clear(k - 1, y - 2, k + 2, y + 2)
        c.fill(k, y - 2, k + 1, y + 2)
        c.fill(k - 1, y - 1, k + 2, y + 1)
    return c


def history():
    c = Canvas()
    c.ring(8, 8, 6.5)
    c.line(8, 8, 8, 4)
    c.line(8, 8, 11, 8)
    return c


def problems():
    c = Canvas()
    c.poly([(8, 1.5), (15, 14), (1, 14)])
    c.clear(7, 6, 8, 10)
    c.clear(7, 11, 8, 12)
    return c


def notes_page():
    c = Canvas()
    c.rect(3, 1, 12, 14)
    c.clear(9, 1, 12, 4)
    c.line(9, 1, 12, 4)
    c.line(9, 1, 9, 4)
    c.line(9, 4, 12, 4)
    c.line(5, 7, 10, 7)
    c.line(5, 10, 10, 10)
    return c


def data():
    c = Canvas()
    c.rect(1, 2, 14, 13)
    c.fill(1, 2, 14, 5)
    c.line(1, 8, 14, 8)
    c.line(1, 11, 14, 11)
    c.line(7, 5, 7, 13)
    return c


def familiar():
    c = Canvas()
    c.poly([(2.5, 2), (7, 6), (2.5, 7)])
    c.poly([(13.5, 2), (9, 6), (13.5, 7)])
    c.fill(2, 6, 13, 13)
    c.clear(4, 8, 5, 9)
    c.clear(10, 8, 11, 9)
    c.clear(7, 11, 8, 11)
    return c


def reload():
    c = Canvas()
    c.ring(8, 8, 5.5)
    c.clear(8, 1, 15, 6)
    c.poly([(9, 0.5), (14.5, 4), (9, 7.5)])
    return c


def log():
    c = Canvas()
    c.rect(1, 2, 14, 13)
    c.line(3, 5, 5, 7)
    c.line(5, 7, 3, 9)
    c.line(7, 9, 11, 9)
    return c


UNDO = undo()
ART = {
    "edit.undo": UNDO,
    "edit.redo": UNDO.mirrored(),
    "file.save": save(),
    "map.fill": fill_bucket(),
    "map.remove_mode": erase(),
    "map.move_mode": move(),
    "map.clone_mode": clone(),
    "map.note": note(),
    "map.run_mode": run(),
    "map.generate": generate(),
    "view.frame": frame(),
    "tools.snip": snip(),
    "panel.outliner": outliner(),
    "panel.library": library(),
    "panel.inspector": inspector(),
    "panel.history": history(),
    "panel.problems": problems(),
    "panel.notes": notes_page(),
    "panel.data": data(),
    "panel.familiar": familiar(),
    "panel.reload": reload(),
    "panel.log": log(),
}


def names():
    text = RUST.read_text()
    block = text.split("// icons:begin")[1].split("// icons:end")[0]
    return re.findall(r'^\s*"([^"]+)",', block, re.M)


def sheet(order):
    rows = -(-len(order) // COLUMNS)
    img = Image.new("RGBA", (COLUMNS * CELL, rows * CELL), (0, 0, 0, 0))
    for i, name in enumerate(order):
        cx, cy = i % COLUMNS * CELL, i // COLUMNS * CELL
        for y in range(CELL):
            for x in range(CELL):
                if ART[name].on[y][x]:
                    img.putpixel((cx + x, cy + y), (255, 255, 255, 255))
    return img


def main():
    order = names()
    missing = [n for n in order if n not in ART]
    unused = [n for n in ART if n not in order]
    if missing or unused:
        sys.exit(f"icons.rs and make_icons.py disagree: no drawing for {missing}, not listed in icons.rs: {unused}")
    img = sheet(order)
    OUT.parent.mkdir(parents=True, exist_ok=True)
    img.save(OUT, optimize=True)
    print(f"{OUT.relative_to(ROOT)}: {len(order)} icons, {img.width}x{img.height}")
    if "--preview" in sys.argv:
        bg = Image.new("RGBA", img.size, (40, 44, 52, 255))
        bg.alpha_composite(img)
        bg.resize((img.width * 12, img.height * 12), Image.NEAREST).save("/tmp/icons_preview.png")


if __name__ == "__main__":
    main()
