#!/usr/bin/env python3
"""**Ask a decision model whether the What's new page's sentences are readable** (`feedback-1793905698793`).

The note: *"These boxes like this are are hard to read. The prose are bad. … Could we actually use a
decision model to run all labels and prose through to make sure it is human readable?"* Its first half
was a measure defect and was fixed in `launcher.rs` (`NEWS_MEASURE_PX`). **This is the second half**: the
sentences themselves, judged by a model rather than by whoever wrote them.

It is not a second decision engine. The policy is `bevy_oracle::run_checks`, reached through
`decide_check --facts`, exactly as `tools/decide/check.py` reaches it for pictures: this script writes the
page's own entries into the shape a `facts` check reads and hands them over. **One implementation of "ask
a model and read the answer"** is the rule this repository keeps.

    python3 tools/decide/news_prose.py                     # the sentences it would send, and the question
    python3 tools/decide/news_prose.py --ask               # ask the model
    python3 tools/decide/news_prose.py --ask --bar 0.6     # fail the gate at p(yes) >= 0.6

exit 0 — nothing below the bar answered "not readable", or nothing was asked;
exit 1 — a sentence at or above `--bar` reads as not-human-readable, naming it;
exit 2 — the run could not be made (no CHANGELOG, a bad argument, the model unreachable).

**The question is phrased declaratively** ("This sentence is hard to read"), because a `noul` head asked
an interrogative returns p≈0 on some models and the answer means nothing — the harness finding recorded in
the home-cloud runbook for laya's `noul` head applies to any `noul`-style question.
"""
import argparse
import json
import os
import subprocess
import sys
import tempfile
from pathlib import Path

REPO = Path(__file__).resolve().parents[2]
CHANGELOG = REPO / "CHANGELOG.md"

# **How many entries the page shows**, matching `launcher::NEWS_SHOWN`. Only these are what a person reads
# on the page; an older sentence is history, and the page does not show it.
NEWS_SHOWN = 10

# The check's name: what a finding quotes back.
CHECK = "news_sentence_is_readable"

# **What "human readable" is asked as**: a declamatory statement the model answers with a probability, and
# the bar that makes it a finding. The rule below is the question's own criterion, so the answer is about
# what a person would say rather than about the model's taste.
QUESTION = (
    "This sentence is hard for an ordinary person to read: it packs more than one idea into a single "
    "sentence, leans on jargon or a file name, or is written as a changelog entry rather than as "
    "something a person would say out loud."
)


def entries(text):
    """`(id, sentence)` for the entries the page lists, newest first: the `*For you:*` line of each.

    The same parse the launcher uses (`launcher::news`), kept here in its smallest form rather than shared
    through a binary: this is a checker of the file, and the launcher is the reader of it.
    """
    found = []
    for line in text.splitlines():
        if not line.startswith("- **"):
            continue
        rest = line[4:]
        if "**" not in rest:
            continue
        ident, rest = rest.split("**", 1)
        if " *For you: " not in rest:
            continue
        # The sentence ends at the `*` that closes the italic span, or at the line's end.
        sentence = rest.split(" *For you: ", 1)[1]
        sentence = sentence.split("*", 1)[0].strip() if "*" in sentence else sentence.strip()
        if sentence:
            found.append((ident.strip(), sentence))
    return found[:NEWS_SHOWN]


def checks_file():
    """A `checks.ron` of one check, held in a temporary project so nothing of this repo's is edited.

    **One line per string, escaped** — RON has no implicit concatenation, so a question split across
    source lines is a parse error, not a longer sentence.
    """
    return (
        "// Generated by tools/decide/news_prose.py: one check over the What's new page's sentences.\n"
        "(\n"
        "    version: 1,\n"
        "    checks: [\n"
        "        (\n"
        f'            name: "{CHECK}",\n'
        f'            question: {json.dumps(QUESTION)},\n'
        "            images: [],\n"
        "            facts: true,\n"
        "            threshold: 0.70,\n"
        "            calibration: None,\n"
        "        ),\n"
        "    ],\n"
        ")\n"
    )


def main(argv):
    ap = argparse.ArgumentParser(description="Ask a decision model whether What's new reads as English.")
    ap.add_argument("--ask", action="store_true", help="ask the model; without it, say what would be asked")
    ap.add_argument("--bar", type=float, default=0.7, help="the probability at which a sentence is a finding")
    ap.add_argument("--json", action="store_true", help="print the verdict as JSON")
    ap.add_argument("--changelog", default=str(CHANGELOG), help="the file to read the sentences from")
    args = ap.parse_args(argv)

    source = Path(args.changelog)
    if not source.is_file():
        print(f"{source} is not a file: there are no sentences to read", file=sys.stderr)
        return 2
    rows = entries(source.read_text(encoding="utf-8"))
    if not rows:
        print(f"no entry in {source} has a *For you:* sentence, so the page shows nothing to judge", file=sys.stderr)
        return 2

    if not args.ask:
        print(f"{len(rows)} sentence(s) on the page, in the order it shows them:\n")
        for ident, sentence in rows:
            print(f"  {ident}\n    {sentence}\n")
        print("The question each is asked, as one state of facts:\n")
        print(f"  {QUESTION}\n")
        print("Run with --ask to put that to the decision model.")
        return 0

    with tempfile.TemporaryDirectory(prefix="news_prose_") as scratch:
        scratch = Path(scratch)
        # **The facts are the page's own entries**, so the check reads what the page shows rather than a
        # summary of it.
        facts = scratch / "facts.json"
        facts.write_text(json.dumps({"entries": [{"id": i, "sentence": s} for i, s in rows]}, indent=2), encoding="utf-8")
        # **A project, in the shape `bevy_oracle` reads one**: `<project>/assets/grimoire/checks.ron`, which
        # is where a game's own checks live. Writing it anywhere else would be a second convention for the
        # same file, and `for_project` would quietly answer with the built-in set instead.
        project = scratch / "project"
        (project / "assets" / "grimoire").mkdir(parents=True)
        (project / "assets" / "grimoire" / "checks.ron").write_text(checks_file(), encoding="utf-8")
        cmd = [
            "cargo", "run", "-q", "-p", "bevy_oracle", "--bin", "decide_check", "--",
            "--captures", str(scratch),
            "--project", str(project),
            "--facts", str(facts),
            "--bar", str(args.bar),
            "--no-builtin",
            "--ask",
        ]
        if args.json:
            cmd.append("--json")
        if os.environ.get("NEWS_PROSE_DRY"):
            print(" ".join(cmd))
            return 0
        return subprocess.call(cmd)


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
